const DAY = 24 * 60 * 60 * 1000;

function ago(days: number, hours = 0) {
  return new Date(Date.now() - days * DAY - hours * 60 * 60 * 1000).toISOString();
}

function dayOf(daysAgo: number) {
  return new Date(Date.now() - daysAgo * DAY).toISOString().slice(0, 10);
}

