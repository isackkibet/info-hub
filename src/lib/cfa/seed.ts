type TxnSeed = [
  id: string,
  transactionType: InventoryTransaction["transactionType"],
  nurseryId: string,
  speciesId: string,
  quantity: number,
  daysAgo: number,
  source: string,
  extra?: Partial<InventoryTransaction>,
];

function txn([
  id,
  transactionType,
  nurseryId,
  speciesId,
  quantity,
  daysAgo,
  source,
  extra,
]: TxnSeed): InventoryTransaction {
  return {
    id,
    transactionType,
    nurseryId,
    speciesId,
    quantity,
    direction: extra?.direction ?? "IN",
    date: dayOf(daysAgo),
    source,
    recordedBy: extra?.recordedBy ?? "Achieng",
    verificationStatus: extra?.verificationStatus ?? "VERIFIED",
    createdAt: ago(daysAgo),
    ...extra,
  };
}

